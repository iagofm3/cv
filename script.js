document.addEventListener("DOMContentLoaded", () => {
  let currentLang = localStorage.getItem("cv-lang") || "es";
  let currentTheme = localStorage.getItem("cv-theme") || "dark";

  // Initialize Theme
  document.documentElement.setAttribute("data-theme", currentTheme);

  const themeToggle = document.getElementById("themeToggle");
  themeToggle.addEventListener("click", () => {
    currentTheme = currentTheme === "dark" ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", currentTheme);
    localStorage.setItem("cv-theme", currentTheme);
  });

  // Initialize Language
  const applyLanguage = (lang) => {
    document.documentElement.lang = lang;
    const dict = translations[lang];
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll("[data-lang-indicator]").forEach((pill) => {
      pill.classList.toggle("active", pill.getAttribute("data-lang-indicator") === lang);
    });
  };

  applyLanguage(currentLang);

  const langToggle = document.getElementById("langToggle");
  langToggle.addEventListener("click", () => {
    currentLang = currentLang === "es" ? "en" : "es";
    localStorage.setItem("cv-lang", currentLang);
    applyLanguage(currentLang);
  });

  // Experience Filter
  const expFilterBtns = document.querySelectorAll("[data-exp-filter]");
  const expItems = document.querySelectorAll("[data-exp-category]");

  expFilterBtns.forEach((btn) => {
    btn.addEventListener("click", () => {
      const filter = btn.getAttribute("data-exp-filter");
      expFilterBtns.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      expItems.forEach((item) => {
        const cat = item.getAttribute("data-exp-category");
        if (filter === "all" || cat === filter) {
          item.classList.remove("is-hidden");
        } else {
          item.classList.add("is-hidden");
        }
      });
    });
  });

  // Skills Filter
  const skillFilterBtns = document.querySelectorAll("[data-skill-filter]");
  const skillCards = document.querySelectorAll("[data-skill-category]");
  const skillsGrid = document.querySelector(".skills-grid");

  skillFilterBtns.forEach((btn) => {
    btn.addEventListener("click", () => {
      const filter = btn.getAttribute("data-skill-filter");
      skillFilterBtns.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      skillCards.forEach((card) => {
        const cat = card.getAttribute("data-skill-category");
        if (filter === "all" || cat === filter) {
          card.classList.remove("is-hidden");
        } else {
          card.classList.add("is-hidden");
        }
      });

      skillsGrid.style.gridTemplateColumns = filter === "all" ? "" : "1fr";
    });
  });

  // Interactive Terminal Toolkit Tabs
  const termTabs = document.querySelectorAll(".t-tab");
  const termPanes = document.querySelectorAll(".t-pane");

  termTabs.forEach((tab) => {
    tab.addEventListener("click", () => {
      const target = tab.getAttribute("data-tab");
      termTabs.forEach((t) => t.classList.remove("active"));
      termPanes.forEach((p) => p.classList.remove("active"));

      tab.classList.add("active");
      document.getElementById(`pane-${target}`).classList.add("active");
    });
  });

  // Print / Export PDF
  const handlePrint = () => window.print();
  document.getElementById("printBtn").addEventListener("click", handlePrint);
  document.getElementById("footerPrintBtn").addEventListener("click", handlePrint);
});
